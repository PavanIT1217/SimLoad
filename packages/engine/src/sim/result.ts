import type { CompiledGraph } from '../model/graph';
import type { ComponentKind, FaultKind } from '../model/types';
import type { LatencySummary } from '../metrics/percentiles';
import type { FlowResult, NodeFlow } from './flow';
import type { NodeOutcome } from './propagation';
import type { RequestTrace } from './sampler';
import type { NodeRuntime } from './state';

/** Per-node metrics for one tick. Rates are req/s. */
export interface NodeTickState {
  id: string;
  kind: ComponentKind;
  inflowRps: number;
  readRps: number;
  writeRps: number;
  capacityRps: number;
  servedRps: number;
  droppedRps: number;
  /** Calls into this node that fail end to end (drops, errors, timeouts, downstream failures). */
  errorRps: number;
  /** Extra downstream calls generated by this node's retries. */
  retryRps: number;
  /** processed / capacity, 0..1 (max over pools). */
  utilization: number;
  /** offered / capacity, can exceed 1 (max over pools). */
  saturation: number;
  queueDepth: number;
  /** Mean time spent at this node (service + queueing + injected). */
  latencyMs: number;
  /** Mean end-to-end latency of a call into this node. */
  e2eLatencyMs: number;
  successRate: number;
  timeoutRate: number;
  instances: number;
  failed: boolean;
  hitRatio: number;
  faults: FaultKind[];
}

export interface TickResult {
  tick: number;
  timeMs: number;
  offeredRps: number;
  /** Successful end-to-end responses per second (goodput). */
  throughputRps: number;
  /** Fraction of offered requests that fail end to end (flow layer). */
  errorRate: number;
  /** Fraction of sampled requests that failed this tick. */
  sampledErrorRate: number;
  /** Total retry traffic across all nodes. */
  retryRps: number;
  /** Rolling end-to-end latency percentiles from sampled requests. */
  latency: LatencySummary;
  nodes: Record<string, NodeTickState>;
  /** Flow on each edge in req/s, including retries. */
  edges: Record<string, number>;
  traces: RequestTrace[];
}

function weighted(read: number, write: number, readRps: number, writeRps: number): number {
  const total = readRps + writeRps;
  return total > 0 ? (read * readRps + write * writeRps) / total : (read + write) / 2;
}

export function buildNodeState(
  flow: NodeFlow,
  outcome: NodeOutcome,
  runtime: NodeRuntime,
): NodeTickState {
  let capacityRps = 0;
  let servedRps = 0;
  let droppedRps = 0;
  let utilization = 0;
  let saturation = 0;
  let queueDepth = 0;
  for (const pool of flow.pools.values()) {
    capacityRps += flow.failed ? 0 : pool.spec.capacityRps;
    servedRps += pool.result.processedRead + pool.result.processedWrite;
    droppedRps += pool.result.droppedRead + pool.result.droppedWrite;
    utilization = Math.max(utilization, pool.result.utilization);
    saturation = Math.max(saturation, pool.result.saturation);
    queueDepth += pool.result.backlog;
  }
  const { read, write } = flow.inflow;
  const inflowRps = read + write;
  if (flow.node.kind === 'client') servedRps = inflowRps;
  const successRate = weighted(outcome.read.success, outcome.write.success, read, write);
  return {
    id: flow.node.id,
    kind: flow.node.kind,
    inflowRps,
    readRps: read,
    writeRps: write,
    capacityRps,
    servedRps,
    droppedRps,
    errorRps: inflowRps * (1 - successRate),
    retryRps: flow.retryRps,
    utilization,
    saturation,
    queueDepth,
    latencyMs: weighted(outcome.read.localLatencyMs, outcome.write.localLatencyMs, read, write),
    e2eLatencyMs: weighted(outcome.read.latencyMs, outcome.write.latencyMs, read, write),
    successRate,
    timeoutRate: weighted(outcome.read.timeoutRate, outcome.write.timeoutRate, read, write),
    instances: runtime.instances,
    failed: flow.failed,
    hitRatio: flow.hitRatio,
    faults: [...runtime.faults.keys()],
  };
}

export interface SystemTotals {
  throughputRps: number;
  errorRate: number;
  retryRps: number;
}

/** Goodput and error rate as seen by the clients. */
export function systemTotals(
  graph: CompiledGraph,
  flows: FlowResult,
  outcomes: Map<string, NodeOutcome>,
  offeredRps: number,
): SystemTotals {
  let good = 0;
  for (const id of graph.clients) {
    const flow = flows.nodes.get(id);
    const outcome = outcomes.get(id);
    if (!flow || !outcome) continue;
    good += flow.inflow.read * outcome.read.success + flow.inflow.write * outcome.write.success;
  }
  let retryRps = 0;
  for (const flow of flows.nodes.values()) retryRps += flow.retryRps;
  return {
    throughputRps: good,
    errorRate: offeredRps > 0 ? Math.min(1, Math.max(0, 1 - good / offeredRps)) : 0,
    retryRps,
  };
}

/** Picks the traces worth showing: the slowest, the first failures, then the earliest. */
export function selectTraces(traces: readonly RequestTrace[], max: number): RequestTrace[] {
  if (max <= 0 || traces.length === 0) return [];
  const chosen = new Set<RequestTrace>();
  const slowest = traces.reduce((a, b) => (b.latencyMs > a.latencyMs ? b : a));
  chosen.add(slowest);
  for (const t of traces) {
    if (chosen.size >= Math.ceil(max / 2)) break;
    if (!t.ok) chosen.add(t);
  }
  for (const t of traces) {
    if (chosen.size >= max) break;
    chosen.add(t);
  }
  return [...chosen].sort((a, b) => a.id - b.id);
}
